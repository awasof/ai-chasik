METHOD = """# Мой чек-лист гайда интервью

- Начинаю с разогрева: 2–3 вопроса о человеке, не о продукте
- Спрашиваю о прошлом опыте, а не о будущем: «расскажите, как было в последний раз»
- Один вопрос — одна мысль, без подсказки ответа
- В конце: «что я не спросил, а стоило?»
- Гайд — не больше 60 минут, лучше 45
"""


def write_docx(path, items):
    d = Document()
    for kind, text in items:
        (d.add_heading(text, level=1) if kind == "h" else d.add_paragraph(text))
    d.save(path)


def write_pdf(path, lines):
    pdfmetrics.registerFont(TTFont("DejaVu", FONT))
    c = canvas.Canvas(str(path), pagesize=A4)
    y = A4[1] - 72
    for i, line in enumerate(lines):
        c.setFont("DejaVu", 16 if i == 0 else 11)
        c.drawString(60, y, line)
        y -= 26 if i == 0 else 18
    c.save()


def main():
    with tempfile.TemporaryDirectory() as t:
        d = Path(t) / "inbox-demo"
        d.mkdir()
        write_docx(d / "Бриф финал (2).docx", BRIEF_A)
        (d / "запись 14.11 респ1.md").write_text(INTERVIEW_A, encoding="utf-8")
        (d / "письмо от заказчика.txt").write_text(LETTER_A, encoding="utf-8")
        write_pdf(d / "brief_v3.pdf", BRIEF_B)
        (d / "транскрипт_тест_прототипа.txt").write_text(INTERVIEW_B, encoding="utf-8")
        (d / "РП-118 требования к тесту.txt").write_text(LETTER_B, encoding="utf-8")
        write_docx(d / "Бриф — семейный счёт.docx", BRIEF_C)
        (d / "Интервью_респондент_2.txt").write_text(INTERVIEW_C, encoding="utf-8")
        (d / "Re_ Re_ требования.txt").write_text(LETTER_C, encoding="utf-8")
        (d / "мой чек-лист гайда.md").write_text(METHOD, encoding="utf-8")
        OUT.parent.mkdir(exist_ok=True)
        with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(d.iterdir()):
                z.write(f, f"inbox-demo/{f.name}")
    print(OUT, OUT.stat().st_size, "байт")


if __name__ == "__main__":
    main()
