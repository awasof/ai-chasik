slides = []
notes = {}


def slide_text(value):
    if isinstance(value, str):
        return re.sub(r'(?<!\.)\.(?=[»”’"\'_*]*$)', '', value)
    if isinstance(value, list):
        return [slide_text(item) for item in value]
    if isinstance(value, dict):
        return {key: slide_text(item) for key, item in value.items()}
    return value


def slide(part, minutes, title, *, say, show, **fields):
    number = len(slides) + 1
    visible = {key: slide_text(value) for key, value in fields.items() if key in {"lead", "foot", "take", "body"}}
    slides.append(dict(n=number, part=part, min=minutes, t=slide_text(title), **(fields | visible)))
    notes[str(number)] = {"say": say, "show": show}


